// Discord link preview for the site, built on Discord's Component Embeds:
// https://docs.discord.com/developers/link-previews/component-embeds
//
// This runs at build time (see vite.config.ts), never in the browser.
// Discord does not run JavaScript, so everything must be in the served HTML.

import { domainToUnicode } from "node:url";

import { axon, meowcord, profile, socials } from "./data.ts";


/**
 * Public URL of the deployed site (https://m5rcel.みんな). Discord needs absolute URLs for every
 * image and button. `new URL()` turns the Japanese domain into its ASCII form (punycode),
 * which is the safe form for meta tags and the embed JSON. Override with the SITE_URL env var.
 */
export const SITE_URL = new URL(process.env.SITE_URL ?? "https://m5rcel.みんな").origin;

/** Human-readable host for visible text, e.g. "m5rcel.みんな". */
export const SITE_HOST = domainToUnicode(new URL(SITE_URL).hostname);

export const BANNER = { path: "/embed-banner.png", width: 1200, height: 630 } as const;
/** PNG copy of the Axon logo (Discord thumbnails can't be SVG). Generated by the assets script. */
export const AXON_LOGO_PNG = "/axon-logo.png";

const ACCENT = 0xffffff; // matches the site's white accent

const link = (label: string) => socials.find((s) => s.label === label)!.href;

type Button = { type: 2; style: 5; label: string; url: string };
const button = (label: string, url: string): Button => ({ type: 2, style: 5, label, url });

export function buildComponentEmbed(version: string) {
  const asset = (path: string) => `${SITE_URL}${path}?v=${version}`;

  return {
    component: {
      type: 17, // Container
      accent_color: ACCENT,
      components: [
        {
          type: 9, // Section: name + bio, with the pfp as the thumbnail
          components: [
            {
              type: 10,
              content: `## [${profile.handle}](${SITE_URL})\n**${profile.name}** · ${profile.location}\n${profile.bio}`,
            },
          ],
          accessory: { type: 11, media: { url: asset(profile.avatar) } },
        },
        {
          type: 12, // Media Gallery: the generated banner
          items: [{ media: { url: asset(BANNER.path) }, description: `${profile.handle} banner` }],
        },
        { type: 14, spacing: 1 }, // Separator
        {
          type: 9, // Section: axon, with its logo as the thumbnail
          components: [
            {
              type: 10,
              content: `### [axon](${axon.links[0].href}) \`${axon.version}\`\n${axon.tagline}\n-# also building **[meowcord](${meowcord.href})** with [${meowcord.partner.name}](${meowcord.partner.href})`,
            },
          ],
          accessory: { type: 11, media: { url: asset(AXON_LOGO_PNG) } },
        },
        { type: 14, spacing: 1 }, // Separator
        {
          type: 1, // Action Row: link buttons only (style 5)
          components: [
            button(SITE_HOST, SITE_URL),
            button("github", link("github")),
            button("x", link("x")),
            button("discord", link("discord")),
            button("axon", axon.links[0].href),
          ],
        },
      ],
    },
  };
}

// --- validation against the documented limits ---

const ALLOWED_BUTTON_KEYS = new Set(["id", "type", "url", "style", "label", "emoji", "disabled"]);
const ALLOWED_TYPES = new Set([1, 2, 9, 10, 11, 12, 14, 17]);

type Node = { type: number; [key: string]: unknown };

export function validateComponentEmbed(json: string, payload: { component: Node }) {
  const errors: string[] = [];
  const bytes = new TextEncoder().encode(json).length;
  if (bytes > 3000) errors.push(`payload is ${bytes} bytes (max 3000)`);

  let count = 0;
  let galleryItems = 0;
  const walk = (node: Node, depth: number) => {
    count++;
    if (!ALLOWED_TYPES.has(node.type)) errors.push(`component type ${node.type} is not allowed`);
    if (node.type === 17 && depth > 0) errors.push("a Container cannot contain another Container");
    if (node.type === 2) {
      for (const key of Object.keys(node)) {
        if (!ALLOWED_BUTTON_KEYS.has(key)) errors.push(`button has disallowed key "${key}"`);
      }
      if (node.style !== 5) errors.push("buttons must use link style 5");
      if (!String(node.url ?? "").startsWith("https://")) errors.push(`button url must be https: ${node.url}`);
    }
    if (node.type === 12) galleryItems += (node.items as unknown[]).length;
    for (const child of (node.components as Node[] | undefined) ?? []) walk(child, depth + 1);
    if (node.accessory) walk(node.accessory as Node, depth + 1);
  };
  if (payload.component.type !== 17) errors.push("top-level component must be a Container (17)");
  walk(payload.component, 0);
  if (count > 40) errors.push(`${count} components (max 40)`);
  if (galleryItems > 10) errors.push(`${galleryItems} media gallery items (max 10)`);

  return { bytes, count, errors };
}
